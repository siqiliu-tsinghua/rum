fn installed_builtin_memory_growth_inventory_is_sorted_and_exhaustive() {
    assert_eq!(
        INSTALLED_BUILTIN_MEMORY_GROWTH_INVENTORY.len(),
        if cfg!(feature = "hash") { 643 } else { 637 }
    );
    assert!(
        INSTALLED_BUILTIN_MEMORY_GROWTH_INVENTORY
            .windows(2)
            .all(|entries| entries[0].0 < entries[1].0),
        "the installed builtin memory-growth inventory must stay sorted and unique"
    );

    let mut declared = rum_runtime::core_builtin_specs()
        .iter()
        .map(|spec| (spec.name, spec.memory_growth))
        .collect::<Vec<_>>();
    for family in [
        super::ARITHMETIC_BUILTINS,
        super::LOGIC_BUILTINS,
        super::PREDICATE_BUILTINS,
        super::ASSOCIATION_CORE_BUILTINS,
        super::ASSOCIATION_TRANSFORM_BUILTINS,
        super::BYTE_BUILTINS,
        super::CHARACTER_CLASS_BUILTINS,
        super::COMBINATORICS_BUILTINS,
        super::CONTROL_BUILTINS,
        super::CSV_BUILTINS,
        super::DATETIME_BUILTINS,
        super::FUNCTIONAL_BUILTINS,
        super::INI_BUILTINS,
        super::INTEGER_DIGITS_BUILTINS,
        super::JSON_BUILTINS,
        super::LAZY_BUILTINS,
        super::NUMBER_THEORY_BUILTINS,
        super::CALCULUS_BUILTINS,
        super::POLYNOMIAL_BUILTINS,
        super::RANDOM_BUILTINS,
        super::REWRITE_BUILTINS,
        super::SCHEMA_BUILTINS,
        super::STRING_CORE_BUILTINS,
        super::STRING_TEXT_BUILTINS,
        super::STRING_MATCH_BUILTINS,
        super::STRUCTURE_CORE_BUILTINS,
        super::STRUCTURE_ORDERING_BUILTINS,
        super::TOML_BUILTINS,
        super::XML_BUILTINS,
        super::YAML_BUILTINS,
    ] {
        declared.extend(family.iter().map(|spec| (spec.name, spec.memory_growth)));
    }
    #[cfg(feature = "hash")]
    declared.extend(
        super::DIGEST_BUILTINS
            .iter()
            .map(|spec| (spec.name, spec.memory_growth)),
    );
    declared.sort_by_key(|(name, _)| *name);
    for declaration in &declared {
        let expected = INSTALLED_BUILTIN_MEMORY_GROWTH_INVENTORY
            .iter()
            .find(|(name, _)| *name == declaration.0);
        assert_eq!(
            Some(declaration),
            expected,
            "every raw catalog declaration must match its exact inventory row"
        );
    }
    declared.dedup();
    assert_eq!(
        declared, INSTALLED_BUILTIN_MEMORY_GROWTH_INVENTORY,
        "the raw catalog declarations must cover every inventory row"
    );

    let mut session = Session::new();
    crate::install_core(&mut session);
    let mut actual = session
        .registered_builtin_specs()
        .map(|spec| (spec.name, spec.memory_growth))
        .collect::<Vec<_>>();
    actual.sort_by_key(|(name, _)| *name);

    assert_eq!(actual, INSTALLED_BUILTIN_MEMORY_GROWTH_INVENTORY);
}
